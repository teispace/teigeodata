//! The HTTP and MCP reference pages of the site (phase 7.3), generated from the servers' own
//! definitions: the HTTP routes from [`ENDPOINTS`] (which a unit test holds to the parser), the
//! MCP tools and resource templates from what `tools/list` and `resources/templates/list` give.
//! The test fails when a checked-in page differs; `TG_BLESS=1` writes it.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    reason = "tests: failures panic with their message"
)]

use std::fmt::Write as _;
use std::path::PathBuf;

use serde_json::Value;
use teigeodata_server::http::{ENDPOINTS, FORMAT, Param};
use teigeodata_server::mcp::{
    INSTALL_TOOLS, INSTRUCTIONS, STORE_TOOLS, resource_templates, tool_definitions,
};
use teigeodata_server::query::{Code, Limits};

const GENERATED: &str = "{/* Generated by `TG_BLESS=1 cargo test -p teigeodata-server --all-features --test reference` from the server's own definitions; do not edit. */}";

/// Every code a server answers, in the order the reference lists them.
const CODES: [Code; 9] = [
    Code::InvalidArgument,
    Code::OutOfBounds,
    Code::NotFound,
    Code::MissingComponent,
    Code::Unauthenticated,
    Code::Forbidden,
    Code::RateLimited,
    Code::Unavailable,
    Code::Internal,
];

/// Escapes text for MDX outside code spans (`<`, `{`, `}`), and `|` for a table cell.
fn mdx(text: &str, cell: bool) -> String {
    let mut out = String::with_capacity(text.len() + 8);
    let mut code = false;
    for c in text.chars() {
        match c {
            '`' => {
                code = !code;
                out.push(c);
            }
            '<' if !code => out.push_str("&lt;"),
            '{' | '}' if !code => {
                out.push('\\');
                out.push(c);
            }
            '|' if cell => out.push_str("\\|"),
            '\n' if cell => out.push(' '),
            _ => out.push(c),
        }
    }
    out
}

/// Compares `text` with the checked-in page, or writes it under `TG_BLESS`.
fn check(name: &str, text: &str) {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../site/content/docs/reference")
        .join(name);
    if std::env::var_os("TG_BLESS").is_some() {
        std::fs::write(&path, text).unwrap();
        return;
    }
    let old = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        old == text,
        "{} is out of date: run `TG_BLESS=1 cargo test -p teigeodata-server --all-features --test reference`",
        path.display()
    );
}

fn param_rows(out: &mut String, params: &[Param]) {
    out.push_str("| Parameter | Required | What |\n|---|---|---|\n");
    for p in params {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} |",
            p.name,
            if p.required { "yes" } else { "" },
            mdx(p.doc, true)
        );
    }
}

fn http_page() -> String {
    let mut out = String::from(
        "---\ntitle: HTTP API\ndescription: Every route of tgd serve with its parameters, generated from the server's route table.\n---\n\n",
    );
    out.push_str(GENERATED);
    out.push_str(
        "\n\nEvery route answers `GET` with query parameters. A native route (`/v1/…`) answers \
`{\"results\": [...], \"attribution\": \"...\"}`, or `{\"result\": ..., \"attribution\": \"...\"}` \
for one value; each place has the fields of [a place](/docs/reference/mcp#places), because both \
servers map a place in one place. The Nominatim routes answer Nominatim's own format. How to run \
the server, with examples that ran: [HTTP server](/docs/servers/http).\n\n",
    );
    out.push_str("Every native place route also takes:\n\n");
    param_rows(&mut out, &[FORMAT]);
    out.push_str("\n## Native routes\n");
    let mut nominatim = false;
    for e in ENDPOINTS {
        if !nominatim && !e.path.starts_with("/v1/") {
            nominatim = true;
            out.push_str(
                "\n## Nominatim routes\n\nThe parameters and fields of Nominatim that its clients use; what \
teigeodata cannot fill is left out, never faked. IDs are teigeodata's.\n",
            );
        }
        let _ = write!(out, "\n### `{}`\n\n{}\n\n", e.path, mdx(e.doc, false));
        param_rows(&mut out, e.params);
        out.push_str("\n```http\n");
        for q in e.examples {
            let _ = writeln!(out, "GET {}?{q}", e.path);
        }
        out.push_str("```\n");
    }
    out.push_str(
        "\n## Other routes\n\n| Route | What |\n|---|---|\n\
| `/packs` | The packs served: each one's release, components, places and attribution. |\n\
| `/health` | `{\"status\": \"ok\", \"layers\": n}` while the server answers. |\n\
| `/mcp` | The [MCP server](/docs/reference/mcp), over Streamable HTTP. |\n",
    );
    out.push_str(
        "\n## Errors\n\nA failure answers `{\"error\": {\"code\": \"...\", \"message\": \"...\"}}` with \
the code's HTTP status; a Nominatim route puts the status in `code`. Codes are stable: one may \
be added, none changes its meaning.\n\n| Code | Status | Meaning |\n|---|--:|---|\n",
    );
    for c in CODES {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} |",
            c.name(),
            c.http_status(),
            code_doc(c)
        );
    }
    out
}

/// What a code means, as the reference says it.
fn code_doc(c: Code) -> &'static str {
    match c {
        Code::InvalidArgument => {
            "A parameter does not parse or has no meaning (a bad ID, a latitude past 90°)."
        }
        Code::OutOfBounds => {
            "A parameter is past a server bound: too long a text, too large a `limit`, too far a radius. A query string that is too long answers 414."
        }
        Code::NotFound => "The place is not in the packs, or there is no such route.",
        Code::MissingComponent => "The packs served lack the component that answers this.",
        Code::Unauthenticated => {
            "The caller must say who they are: only a deployment that adds keys answers it."
        }
        Code::Forbidden => {
            "The caller may not ask this: only a deployment that adds rules answers it."
        }
        Code::RateLimited => "Too much, too fast: only a deployment that adds limits answers it.",
        Code::Unavailable => {
            "The server cannot answer now (the request took longer than its timeout); asking again later may work."
        }
        Code::Internal => "The server failed; never the client's fault.",
        other => panic!("document the code {}", other.name()),
    }
}

/// A JSON Schema type as words: `string or null`, `array of string`.
fn ty(s: &Value) -> String {
    let base = match &s["type"] {
        Value::String(t) => t.clone(),
        Value::Array(ts) => ts
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" or "),
        _ if s.get("enum").is_some() => "string".to_owned(),
        _ => "any".to_owned(),
    };
    if base == "array" {
        format!("array of {}", ty(&s["items"]))
    } else {
        base
    }
}

/// A schema's bounds and default, as words.
fn bounds(s: &Value) -> String {
    let mut b = Vec::new();
    let n = |k: &str| s.get(k).map(Value::to_string);
    match (n("minimum").or(n("exclusiveMinimum")), n("maximum")) {
        (Some(lo), Some(hi)) => b.push(format!("{lo} to {hi}")),
        (Some(lo), None) if s.get("exclusiveMinimum").is_some() => b.push(format!("over {lo}")),
        (Some(lo), None) => b.push(format!("at least {lo}")),
        (None, Some(hi)) => b.push(format!("at most {hi}")),
        (None, None) => {}
    }
    match (n("minLength"), n("maxLength")) {
        (Some(lo), Some(hi)) => b.push(format!("{lo} to {hi} bytes")),
        (None, Some(hi)) => b.push(format!("at most {hi} bytes")),
        _ => {}
    }
    match (n("minItems"), n("maxItems")) {
        (Some(lo), Some(hi)) => b.push(format!("{lo} to {hi} items")),
        (None, Some(hi)) => b.push(format!("at most {hi} items")),
        _ => {}
    }
    if let Some(Value::Array(vs)) = s.get("enum") {
        let vs: Vec<String> = vs
            .iter()
            .map(|v| format!("`{}`", v.as_str().unwrap_or("?")))
            .collect();
        b.push(format!("one of {}", vs.join(", ")));
    }
    if let Some(d) = s.get("default") {
        b.push(format!("default `{d}`"));
    }
    b.join("; ")
}

/// One row per property of an object schema, nested objects and arrays of objects flattened
/// as `focus.lat` and `names[].text`.
fn fields(out: &mut String, schema: &Value, prefix: &str, required_too: bool) {
    let Some(props) = schema["properties"].as_object() else {
        return;
    };
    let required: Vec<&str> = schema["required"]
        .as_array()
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut names: Vec<&String> = props.keys().collect();
    names.sort_by_key(|n| (!required.contains(&n.as_str()), *n));
    for name in names {
        let s = &props[name];
        let path = format!("{prefix}{name}");
        let mut what = s["description"].as_str().unwrap_or_default().to_owned();
        let b = bounds(s);
        if !b.is_empty() {
            if !what.is_empty() {
                what.push(' ');
            }
            what.push_str(&b[..1].to_uppercase());
            what.push_str(&b[1..]);
            what.push('.');
        }
        let req = if required.contains(&name.as_str()) {
            "yes"
        } else {
            ""
        };
        if required_too {
            let _ = writeln!(
                out,
                "| `{path}` | {} | {req} | {} |",
                ty(s),
                mdx(&what, true)
            );
        } else {
            let _ = writeln!(out, "| `{path}` | {} | {} |", ty(s), mdx(&what, true));
        }
        if s.get("properties").is_some() {
            fields(out, s, &format!("{path}."), required_too);
        } else if s["items"].get("properties").is_some() {
            fields(out, &s["items"], &format!("{path}[]."), required_too);
        }
    }
}

fn mcp_page() -> String {
    let tools = serde_json::to_value(tool_definitions(&Limits::SERVER)).unwrap();
    let tools = tools.as_array().unwrap();
    let places = &tools[0]["outputSchema"];
    let mut out = String::from(
        "---\ntitle: MCP tools\ndescription: Every tool and resource of tgd mcp with its arguments and answer, generated from the server's own definitions.\n---\n\n",
    );
    out.push_str(GENERATED);
    out.push_str(
        "\n\nWhat `tools/list` and `resources/templates/list` give, with the bounds of a server's \
default limits. Every answer is structured content that its tool's output schema accepts, the \
same object as text, with the attribution under `_meta` too. How to run the server and connect \
a client: [MCP server](/docs/servers/mcp).\n\nThe server's instructions to a client:\n\n",
    );
    let _ = writeln!(out, "> {}\n", mdx(INSTRUCTIONS, false));
    out.push_str("## Tools\n\n| Tool | What |\n|---|---|\n");
    for t in tools {
        let name = t["name"].as_str().unwrap();
        let _ = writeln!(
            out,
            "| [`{name}`](#{name}) | {} |",
            mdx(t["title"].as_str().unwrap_or_default(), true)
        );
    }
    for t in tools {
        let name = t["name"].as_str().unwrap();
        let _ = write!(
            out,
            "\n### `{name}`\n\n**{}.** {}\n\n",
            mdx(t["title"].as_str().unwrap_or_default(), false),
            mdx(t["description"].as_str().unwrap_or_default(), false)
        );
        if STORE_TOOLS.contains(&name) {
            out.push_str("Listed only by a server over a store (`--store`).\n\n");
        }
        if INSTALL_TOOLS.contains(&name) {
            out.push_str(
                "Listed only by a server over a store that allows installs (`--allow-install`).\n\n",
            );
        }
        let a = &t["annotations"];
        let mut hints = vec![if a["readOnlyHint"] == Value::Bool(true) {
            "read-only"
        } else {
            "changes the store"
        }];
        if a["idempotentHint"] == Value::Bool(true) {
            hints.push("idempotent");
        }
        if a["openWorldHint"] == Value::Bool(true) {
            hints.push("reaches the network");
        }
        let _ = writeln!(out, "Hints: {}.\n", hints.join(", "));
        if t["inputSchema"]["properties"]
            .as_object()
            .is_some_and(|p| !p.is_empty())
        {
            out.push_str("| Argument | Type | Required | What |\n|---|---|---|---|\n");
            fields(&mut out, &t["inputSchema"], "", true);
            out.push('\n');
        } else {
            out.push_str("No arguments.\n\n");
        }
        if &t["outputSchema"] == places {
            out.push_str("Answers [places](#places), a page at a time.\n");
        } else {
            out.push_str("Answers:\n\n| Field | Type | What |\n|---|---|---|\n");
            fields(&mut out, &t["outputSchema"], "", false);
        }
    }
    out.push_str(
        "\n## Places\n\nThe answer of every place tool: a page of `results`, the `next_cursor` of the \
next page when there is one, and the `attribution` of the packs that answered. A field a place \
lacks is left out or null.\n\n| Field | Type | What |\n|---|---|---|\n",
    );
    fields(&mut out, places, "", false);
    out.push_str("\n## Resources\n\n| URI template | What | Type |\n|---|---|---|\n");
    for r in resource_templates() {
        let r = serde_json::to_value(r).unwrap();
        let _ = writeln!(
            out,
            "| `{}` | {}: {} | `{}` |",
            r["uriTemplate"].as_str().unwrap_or_default(),
            mdx(r["title"].as_str().unwrap_or_default(), true),
            mdx(r["description"].as_str().unwrap_or_default(), true),
            r["mimeType"].as_str().unwrap_or_default()
        );
    }
    out.push_str(
        "\n## Errors\n\nA tool that fails answers a tool error (`isError`) whose text is \
`{\"error\": {\"code\": \"...\", \"message\": \"...\"}}`, with the codes of the \
[HTTP API](/docs/reference/http#errors).\n",
    );
    out
}

